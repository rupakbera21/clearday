export function matchIndianCities(query: string, limit = 5): LocationResult[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];

  const exactPrefix: LocationResult[] = [];
  const contains: LocationResult[] = [];

  for (const city of INDIAN_CITIES_CATALOG) {
    const nameLower = city.name.toLowerCase();
    const adminLower = (city.admin1 ?? "").toLowerCase();

    if (nameLower.startsWith(q)) {
      exactPrefix.push(city);
    } else if (nameLower.includes(q) || adminLower.includes(q)) {
      contains.push(city);
    }

    if (exactPrefix.length >= limit) {
      return exactPrefix.slice(0, limit);
    }
  }

  return [...exactPrefix, ...contains].slice(0, limit);
}
